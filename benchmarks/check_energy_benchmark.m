%% Energy Benchmark Regression Check
clearvars; clc;

benchmarkDirectory = fileparts(mfilename('fullpath'));
rootDirectory = fileparts(benchmarkDirectory);
addpath(benchmarkDirectory);
addpath(fullfile(rootDirectory, 'examples'));

report = run_energy_benchmark;

assert(report.summary.total_benchmarks == 4, ...
    'Benchmark suite size changed unexpectedly.');
assert(report.summary.failed_benchmarks == 0, ...
    'One or more deterministic energy benchmarks failed.');
assert(report.summary.pass_rate == 1, ...
    'Benchmark pass rate must be 100 percent.');
assert(all(isfinite([ ...
    report.benchmarks.battery_2rc_identification.metrics.calibration_rmse_mV, ...
    report.benchmarks.battery_2rc_identification.metrics.heldout_rmse_mV, ...
    report.benchmarks.battery_soc_ekf.metrics.soc_rmse, ...
    report.benchmarks.battery_thermal_model.metrics.peak_temperature_C, ...
    report.benchmarks.bess_dc_reserve.metrics.final_soc])), ...
    'All benchmark KPI values must be finite.');

repeat = run_energy_benchmark;
assert(isequaln(report.summary, repeat.summary) && ...
    isequaln(report.benchmarks, repeat.benchmarks), ...
    'Benchmark outputs must be deterministic.');

fprintf('Energy benchmark suite passed: %d/%d benchmarks.\n', ...
    report.summary.passed_benchmarks, report.summary.total_benchmarks);
